-- Explicit table, sequence and function grants for authenticated and service_role.
--
-- Why: the local Supabase stack hands every new public table/function to authenticated and service_role by
-- default privileges, so every earlier migration relied on that. The hosted project does not: on it the
-- tables were created with no INSERT/UPDATE/DELETE for authenticated, nothing for service_role, and the RLS
-- helpers (current_app_role, is_active_member) were not executable by authenticated, so nobody could sign in
-- to a working app and create-admin failed with "permission denied for table app_users".
-- This migration states the grants the app has always been tested with (taken from a database built from
-- these migrations), so hosted, local and any future project end up identical. Row-level security still
-- decides which rows; the ledger tables (journal_*, stock_movements, audit_log, app_users writes, doc_sequences)
-- stay read-only or closed exactly as the earlier migrations left them. Idempotent.

